_LATEX_ESCAPES = {"\\": r"\textbackslash{}", "&": r"\&", "%": r"\%", "$": r"\$", "#": r"\#", "_": r"\_", "{": r"\{", "}": r"\}", "~": r"\textasciitilde{}", "^": r"\textasciicircum{}"}
_LATEX_PATTERN = re.compile("|".join(re.escape(x) for x in _LATEX_ESCAPES))
_TRANSLATIONS = {
    "\u2010": "-", "\u2011": "-", "\u2012": "--", "\u2013": "--", "\u2014": "---",
    "\u2018": "`", "\u2019": "'", "\u201c": "``", "\u201d": "''",
    "\u2032": r"$'$", "\u2033": r"$''$", "\u00b0": r"\textdegree{}", "\u2212": "$-$",
    "\u00d7": r"$\times$", "\u00b7": r"$\cdot$", "\u2026": r"\ldots{}",
    "\u2248": r"$\approx$", "\u2264": r"$\leq$", "\u2265": r"$\geq$", "\u2260": r"$\neq$",
    "\u00b1": r"$\pm$", "\u2192": r"$\rightarrow$", "\u2194": r"$\leftrightarrow$",
    "\u03b1": r"$\alpha$", "\u03b2": r"$\beta$", "\u03b3": r"$\gamma$", "\u03b4": r"$\delta$",
    "\u03ba": r"$\kappa$", "\u03bb": r"$\lambda$", "\u03bc": r"$\mu$", "\u03c3": r"$\sigma$",
    "\u03a9": r"$\Omega$", "\u00c5": r"\AA{}", "\u212b": r"\AA{}",
    "\u2080": "$_0$", "\u2081": "$_1$", "\u2082": "$_2$", "\u2083": "$_3$", "\u2084": "$_4$", "\u2085": "$_5$", "\u2086": "$_6$",
    "\u00b9": "$^1$", "\u00b2": "$^2$", "\u00b3": "$^3$", "\u00a0": " ",
}
_TRANSLATION_TABLE = {ord(k): v for k, v in _TRANSLATIONS.items()}
MAX_TABLE_ROWS = 60
_CITE = re.compile(r"\\cite\{([^}]*)\}")
_BIB_ENTRY = re.compile(r"^@\w+\{([^,]+),", re.MULTILINE)


def latex_escape(text: Any) -> str:
    return _LATEX_PATTERN.sub(lambda m: _LATEX_ESCAPES[m.group()], str(text).translate(_TRANSLATION_TABLE))


def unsupported_characters(text: str) -> list[str]:
    return sorted({c for c in str(text).translate(_TRANSLATION_TABLE) if ord(c) > 127})


def citation_keys(documents: Mapping[str, DocumentRecord]) -> dict[str, str]:
    result, seen = {}, {}
    for doc_id in sorted(documents):
        base = documents[doc_id].bib_key()
        count = seen.get(base, 0)
        seen[base] = count + 1
        result[doc_id] = base if count == 0 else f"{base}x{count}"
    return result


def _bib_field(name: str, value: Any) -> str:
    return f"  {name} = {{{latex_escape(value)}}},\n"


def build_bibliography(documents: Mapping[str, DocumentRecord], keys: Mapping[str, str]) -> str:
    chunks = ["% Generated by VeriMat.\n", "% Every body citation has one entry.\n\n"]
    for doc_id in sorted(documents):
        record = documents[doc_id]
        text = f"@article{{{keys[doc_id]},\n  title = {{{{{latex_escape(record.title)}}}}},\n"
        if record.venue:
            text += _bib_field("journal", record.venue)
        if record.year:
            text += f"  year = {{{int(record.year)}}},\n"
        if record.doi:
            text += _bib_field("doi", record.doi)
        text += _bib_field("note", f"{record.database} doc_id {record.doc_id}")
        chunks.append(text.rstrip(",\n") + "\n}\n\n")
    return "".join(chunks)


