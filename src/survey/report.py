def _row(cells: Iterable[Any]) -> str:
    return " & ".join(latex_escape(x) for x in cells) + r" \\" + "\n"


def _cite(doc_keys: Iterable[str], keys: Mapping[str, str]) -> str:
    chosen = [keys[x] for x in dict.fromkeys(doc_keys) if x in keys]
    return "\\cite{" + ",".join(chosen) + "}" if chosen else ""


@dataclass
class SurveyReport:
    files: dict[str, str] = field(default_factory=dict)
    audit: dict[str, Any] = field(default_factory=dict)

    def write(self, root: Any) -> list[str]:
        from src.core.portability import extended_path
        if not self.audit.get("verified"):
            raise SurveyContractError("report citations failed verification: " + canonical_json(self.audit.get("failures", [])))
        target = extended_path(root)
        target.mkdir(parents=True, exist_ok=True)
        for name, content in sorted(self.files.items()):
            (target / name).write_text(content, encoding="utf-8", newline="\n")
        return sorted(self.files)


def verify(*, corpus: SurveyCorpus, extraction: ExtractionResult, gaps: GapResult, tex: str, bib: str, keys: Mapping[str, str]) -> dict[str, Any]:
    failures = []
    def fail(check: str, detail: str) -> None:
        failures.append({"check": check, "detail": detail})
    for relation_id, relation in sorted(extraction.relations.items()):
        passage = corpus.passages.get(relation.passage_id)
        if passage is None:
            fail("relation_passage_present", f"{relation_id} cites {relation.passage_id}")
        elif not passage.supports_quote(relation.quote):
            fail("relation_quote_literal", relation_id)
        elif corpus.document_for(passage) is None:
            fail("relation_document_present", relation_id)
    for gap_id, gap in sorted(gaps.gaps.items()):
        cited = [x for x in gap.supporting_passages if x in corpus.passages]
        if len(cited) != len(gap.supporting_passages):
            fail("gap_passages_present", gap_id)
        if gap.novelty == "known" and not any(corpus.passages[x].supports_quote(gap.novelty_quote) for x in cited):
            fail("gap_novelty_quote_literal", gap_id)
    cited_keys = {x.strip() for group in _CITE.findall(tex) for x in group.split(",") if x.strip()}
    bib_keys = set(_BIB_ENTRY.findall(bib))
    for key in sorted(cited_keys - bib_keys):
        fail("citation_has_entry", key)
    for key in sorted(bib_keys - cited_keys):
        fail("entry_is_cited", key)
    reverse = {value: key for key, value in keys.items()}
    for key in sorted(bib_keys):
        record = corpus.documents.get(reverse.get(key, ""))
        if record is None:
            fail("entry_has_document", key)
        elif not record.is_citable():
            fail("entry_is_findable", key)
    return {"verified": not failures, "n_checks_failed": len(failures), "failures": failures,
            "n_relations_checked": len(extraction.relations), "n_gaps_checked": len(gaps.gaps),
            "n_citations_in_body": len(cited_keys), "n_bibliography_entries": len(bib_keys),
            "citations_match_bibliography": not any(x["check"] in {"citation_has_entry", "entry_is_cited"} for x in failures),
            "characters_pdflatex_cannot_set": sorted({c for text in (tex, bib) for c in unsupported_characters(text)}),
            "novelty_audit": novelty_audit(gaps, corpus)}


def _scope_section(corpus: SurveyCorpus, coverage: Mapping[str, Any]) -> str:
    topic = corpus.topic
    protocol = coverage["protocol"]
    return ("\\section{Scope and retrieval protocol}\n" + f"Topic: {latex_escape(topic.title)}. "
            f"Language: {latex_escape(topic.language)}. Years: {topic.year_from}--{topic.year_to}. "
            f"Databases: {latex_escape(', '.join(coverage['databases']))}. Fingerprint: "
            f"\\texttt{{{latex_escape(coverage['topic_fingerprint'])}}}.\n\n"
            f"Stage one: {latex_escape(protocol['stage_one'])}; passes: "
            f"{latex_escape(protocol['stage_one_passes'])}. Stage two: "
            f"{latex_escape(protocol['stage_two'])}. {latex_escape(protocol['anchoring_bias'].capitalize())}.\n\n"
            "The stages are not interchangeable. Semantic retrieval on this deployment enforces "
            "exactly one hard constraint, the document scope, so the year and language envelope is "
            "a property of the corpus only because the metadata stage established it first.\n\n")


def _coverage_section(coverage: Mapping[str, Any]) -> str:
    out = "\\section{Coverage}\n\\begin{tabular}{lr}\n\\toprule\nQuantity & Value \\\\\n\\midrule\n"
    for label, key in (("Queries", "n_queries"), ("Empty queries", "n_empty_queries"), ("Saturated queries", "n_saturated_queries"), ("Documents", "n_documents"), ("Citable documents", "n_citable_documents"), ("Documents with evidence", "n_documents_with_evidence"), ("Unread documents", "n_documents_unread"), ("Passages", "n_passages")):
        out += _row((label, coverage[key]))
    span = coverage["year_span"]
    out += _row(("Year span", f"{span[0]}--{span[1]}")) + "\\bottomrule\n\\end{tabular}\n\n"
    total = max(1, int(coverage["n_documents"]))
    out += f"{coverage['n_documents_unread']} of {coverage['n_documents']} documents ({100 * coverage['n_documents_unread'] / total:.1f} per cent) were unread; negative claims are bounded by this fraction.\n\n"
    if coverage["queries_returning_nothing"]:
        out += "Queries returning nothing:\n\\begin{itemize}\n" + "".join(f"\\item {latex_escape(x)}\n" for x in coverage["queries_returning_nothing"]) + "\\end{itemize}\n"
    return out + "\n"


def _gate_section(extraction: Mapping[str, Any], candidates: Mapping[str, Any]) -> str:
    out = "\\section{Deterministic gates}\nA language model proposed relations; none was admitted on its word.\n\n\\begin{tabular}{lr}\n\\toprule\nQuantity & Value \\\\\n\\midrule\n"
    for label, key in (("Proposed", "n_proposed"), ("Admitted", "n_admitted"), ("Rejected", "n_rejected"), ("Admission rate", "admission_rate")):
        out += _row((label, extraction[key]))
    for key, value in sorted(extraction["rejections_by_reason"].items()):
        out += _row((f"Rejected: {key}", value))
    out += _row(("Gap candidates", candidates["n_candidates"])) + _row(("Cap suppressions", candidates["suppressed_by_per_kind_cap"]))
    return out + "\\bottomrule\n\\end{tabular}\n\n"


def _relation_section(rows: list[Mapping[str, Any]], keys: Mapping[str, str], max_rows: int) -> str:
    out = "\\section{Structure--property relations}\n\\begin{longtable}{p{22mm}p{26mm}p{24mm}p{16mm}p{20mm}p{14mm}l}\n\\toprule\nMaterial & Feature & Property & Direction & Value & Method & Source \\\\\n\\midrule\n\\endfirsthead\\toprule\nMaterial & Feature & Property & Direction & Value & Method & Source \\\\\n\\midrule\\endhead\\bottomrule\\endfoot\n"
    for row in rows[:max_rows]:
        value = f"{row['value']} {row['unit']}".strip()
        if row["temperature_k"]:
            value += f" at {row['temperature_k']} K"
        cells = (row["material"], row["structural_feature"], row["property_name"], row["direction"], value, row["method"])
        out += " & ".join(latex_escape(x) for x in cells) + " & " + _cite([row["evidence"]["doc_id"]], keys) + r" \\" + "\n"
    out += "\\end{longtable}\n\n"
    if len(rows) > max_rows:
        out += f"{len(rows) - max_rows} further relations are retained in relations.json and the evidence chain.\n\n"
    return out


def _gap_section(rows: list[Mapping[str, Any]], keys: Mapping[str, str]) -> str:
    out = "\\section{Research gaps}\n"
    for row in rows:
        out += f"\\subsection*{{{latex_escape(row['statement'][:80])}}}\n\\textbf{{Gap.}} {latex_escape(row['statement'])}\n\n"
        out += f"\\textbf{{Status.}} {latex_escape(row['novelty'])}; {latex_escape(row['novelty_basis'])}.\n"
        if row["novelty_quote"]:
            out += "\\begin{quote}" + latex_escape(row["novelty_quote"]) + "\\end{quote}\n"
        derivation = row["derivation"]
        out += f"\\textbf{{Derivation.}} {latex_escape(derivation['rule'])}; {latex_escape(derivation['subject'])}; {latex_escape('; '.join(map(str, derivation['facts'])))}.\n"
        evidence = row["evidence"]
        out += f"\\textbf{{Evidence.}} {len(evidence)} passages {_cite([x['doc_id'] for x in evidence], keys)}; identifier \\texttt{{{latex_escape(row['gap_id'])}}}.\n\n"
    return out


def _chain_section(rows: list[Mapping[str, Any]], keys: Mapping[str, str]) -> str:
    out = "\\section{Evidence chain}\n\\label{sec:chain}\n"
    for row in rows:
        evidence = row["evidence"]
        out += f"\\noindent\\texttt{{{latex_escape(row['relation_id'])}}} {_cite([evidence['doc_id']], keys)}\n\\begin{{quote}}{latex_escape(row['quote'])}\\end{{quote}}\n"
        parts = [evidence["database"], evidence["doc_id"], evidence["passage_id"], str(evidence["content_sha256"])[:16], evidence["query_id"]]
        out += "{\\small " + latex_escape("; ".join(map(str, parts))) + "}\n\n"
    return out


def _disclosure_section(audit: Mapping[str, Any], extraction: Mapping[str, Any], gaps: Mapping[str, Any], coverage: Mapping[str, Any], model_route: str) -> str:
    novelty = audit["novelty_audit"]
    out = f"\\section{{Disclosure and verification}}\nLiterature source: Sciverse API. Model route: {latex_escape(model_route)}. Deterministic gates decide admissibility.\n\n\\begin{{tabular}}{{lr}}\n\\toprule\nCheck & Result \\\\\n\\midrule\n"
    for label, value in (("Relations checked", audit["n_relations_checked"]), ("Gaps checked", audit["n_gaps_checked"]), ("Body citations", audit["n_citations_in_body"]), ("Bibliography entries", audit["n_bibliography_entries"]), ("Failures", audit["n_checks_failed"]), ("Known gaps", novelty["n_known"]), ("New gaps", novelty["n_new"]), ("Novelty verified", novelty["verified"]), ("Extraction calls", extraction["model_calls"]), ("Gap calls", gaps["model_calls"])):
        out += _row((label, value))
    return out + "\\bottomrule\n\\end{tabular}\n\n"


def build_report(*, corpus: SurveyCorpus, extraction: ExtractionResult, candidates: CandidateSet, gaps: GapResult, title: str, author: str = "taiwanhuachenyu", report_date: str = "", model_route: str = "claude-code", max_table_rows: int = MAX_TABLE_ROWS) -> SurveyReport:
    coverage = coverage_report(corpus)
    relations = relation_table(extraction, corpus)
    gap_rows = gap_table(gaps, candidates, corpus)
    cited = {str(x["evidence"]["doc_id"]) for x in relations}
    cited.update(str(x["doc_id"]) for row in gap_rows for x in row["evidence"])
    documents = {doc_id: record for doc_id, record in corpus.documents.items() if doc_id in cited and record.is_citable()}
    keys = citation_keys(documents)
    tex = PREAMBLE + f"\\title{{{latex_escape(title)}}}\n\\author{{{latex_escape(author)}}}\n\\date{{{latex_escape(report_date)}}}\n\\begin{{document}}\n\\maketitle\n\\tableofcontents\n\n"
    tex += _scope_section(corpus, coverage) + _coverage_section(coverage) + _gate_section(extraction.manifest(), candidates.manifest())
    tex += _relation_section(relations, keys, max_table_rows) + _gap_section(gap_rows, keys) + _chain_section(relations, keys)
    bib = build_bibliography(documents, keys)
    audit = verify(corpus=corpus, extraction=extraction, gaps=gaps, tex=tex, bib=bib, keys=keys)
    audit["documents_cited_but_not_citable"] = sorted(cited - set(documents))
    tex += _disclosure_section(audit, extraction.manifest(), gaps.manifest(), coverage, model_route)
    tex += "\\bibliographystyle{unsrt}\n\\bibliography{references}\n\\end{document}\n"
    files = {"survey.tex": tex, "references.bib": bib, "build.py": BUILD_SCRIPT, "Makefile": MAKEFILE,
             "coverage.json": canonical_json(coverage) + "\n", "relations.json": canonical_json(relations) + "\n",
             "gaps.json": canonical_json(gap_rows) + "\n", "verification.json": canonical_json(audit) + "\n",
             "extraction_gates.json": canonical_json({"extraction": extraction.manifest(), "candidates": candidates.manifest(), "gaps": gaps.manifest(), "rejected_proposals": [item.__dict__ for item in extraction.rejections], "refused_candidates": [item.__dict__ for item in gaps.refused], "dropped_by_gate": list(gaps.dropped)}) + "\n"}
    return SurveyReport(files=files, audit=audit)
